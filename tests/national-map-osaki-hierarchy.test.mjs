import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const read=p=>fs.readFileSync(p,'utf8');
test('national map has Osaki municipality assessment and verified city-hall representative point',()=>{
  const source=JSON.parse(read('data/research-municipalities.json'));
  const index=JSON.parse(read('data/research-map-index.json'));
  const pins=JSON.parse(read('data/map-pins.json'));
  const m=source.municipalities.filter(x=>x.id==='osaki');
  assert.equal(m.length,1,'Osaki must not have duplicate prefecture/catalog pins');
  assert.equal(m[0].name,'大崎市');
  assert.equal(m[0].prefecture,'宮城県');
  assert.deepEqual(m[0].coordinates,[38.577222,140.955556]);
  assert.match(m[0].coordinateNote,/学校所在地を示すものではありません/);
  assert.match(m[0].sources.find(x=>x.id==='official-location').url,/city\.osaki\.miyagi\.jp/);
  assert.equal(m[0].url,'/research/osaki.html');
  assert.equal(m[0].status,'published-research');
  assert.equal(m[0].preservePublishedReport,true);
  assert.equal(m[0].schoolReportCount,25);
  assert.deepEqual(pins.regions.osaki,[647,484]);
  assert.equal(index.municipalities.length,30);
  assert.equal(index.municipalities.filter(x=>x.id==='osaki').length,1);
  assert.equal(index.municipalities.find(x=>x.id==='osaki').url,'/research/osaki.html');
  assert.equal(index.municipalities.find(x=>x.id==='osaki').schoolReportCount,25);
  assert.equal(index.municipalities.find(x=>x.id==='osaki').schools.length,0,
    'school report count must not be misrepresented as archive originals');
});
test('existing nationwide interactive map indexes Osaki with direct municipal report navigation',()=>{
  const html=read('research-map.html');
  const app=read('assets/app.js');
  const js=read('js/research-map.js');
  const home=read('index.html');
  assert.match(html,/id="research-city"[^]*?<option>大崎市<\/option>/);
  assert.match(html,/data-region="osaki"/);
  assert.match(html,/href="research\/osaki\.html"/);
  assert.match(html,/学校別評価25校/);
  assert.match(html,/全国PTA研究地図/);
  assert.match(js,/schoolReportCount/);
  assert.match(app,/status==='published-research'&&m.url\?localLink\(m.url\)/);
  assert.match(home,/id="map"/);
  assert.match(home,/href="research-map\.html"/);
  assert.match(home,/href="research\/osaki\.html"/);
});
test('the linked navigation tiers and generated-file protection are explicit',()=>{
  const city=read('research/osaki.html');
  const school=read('archive/osaki/naruko-compulsory/index.html');
  const reader=read('assets/osaki-evidence-report.js');
  const generator=read('scripts/generate-research-map.js');
  const guide=read('ai-system/report-standards/PARENT_FACING_SKILL.md');
  assert.match(city,/href="\/research-map\.html"/);
  assert.match(city,/id="schools"/);
  assert.match(city,/href="\/archive\/osaki\/naruko-compulsory\/"/);
  assert.match(reader,/全国調査マップ/);
  assert.match(reader,/大崎市の総合評価/);
  assert.match(school,/osaki-evidence-report\.js/);
  assert.match(generator,/if \(m\.preservePublishedReport\)/);
  assert.match(generator,/Protected municipal report missing/);
  assert.match(guide,/全国調査マップ → 市の総合評価 → 学校の個別評価/);
});
